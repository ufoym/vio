#!/usr/bin/env python3
"""Regenerates docs/data.js from the tables in README.md.

    python3 docs/gen_data.py

The project page reads every number it shows from data.js, so rerun this
after the README's feature or performance tables change.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def split_row(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def tables(lines):
    """Yields (caption, header, rows, notes, section) for every Markdown table."""
    i, section = 0, ""
    while i < len(lines):
        if lines[i].startswith("#"):
            section = lines[i].lstrip("#").strip()
        if lines[i].startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s:|-]+\|$", lines[i + 1]):
            # Caption: the paragraph just above the table.
            j = i - 1
            while j >= 0 and not lines[j].strip():
                j -= 1
            cap = []
            while j >= 0 and lines[j].strip() and not lines[j].startswith(("#", "|")):
                cap.insert(0, lines[j].strip())
                j -= 1
            header = split_row(lines[i])
            rows, i = [], i + 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(split_row(lines[i]))
                i += 1
            # Notes: the paragraph just below, when it is footnotes.
            k = i
            while k < len(lines) and not lines[k].strip():
                k += 1
            notes = []
            while k < len(lines) and lines[k].strip() and lines[k][0] in "¹²³⁴⁵⁶⁷⁸⁹":
                notes.append(lines[k].strip())
                k += 1
                while k < len(lines) and lines[k].strip() and lines[k][0] not in "¹²³⁴⁵⁶⁷⁸⁹#|":
                    notes[-1] += " " + lines[k].strip()
                    k += 1
            yield " ".join(cap), header, rows, notes, section
        else:
            i += 1


def pct(cell):
    """'+39%' -> 1.39, '−8%' -> 0.92, '—' -> None."""
    m = re.match(r"^([+−-])(\d+(?:\.\d+)?)%", cell)
    if not m:
        return None
    v = float(m.group(2)) / 100
    return round(1 + (v if m.group(1) == "+" else -v), 4)


def main():
    lines = (ROOT / "README.md").read_text(encoding="utf-8").splitlines()
    out = {"features": [], "perf": {}}
    for cap, header, rows, notes, section in tables(lines):
        if header[0] == "Feature":
            out["features"].append({"header": header, "rows": rows, "notes": notes})
            continue
        key = None
        if section == "JPEG":
            if cap.startswith("JPEG compression:"):
                key = "jpeg_enc"
            elif cap.startswith("JPEG decompression:"):
                key = "jpeg_dec"
            elif cap.startswith("JPEG compression, vio"):
                key = "jpeg_enc_cfg"
            elif cap.startswith("JPEG decompression, vio"):
                key = "jpeg_dec_cfg"
        elif section == "PNG":
            if cap.startswith("PNG decoding"):
                key = "png_dec"
            elif cap.startswith("PNG encoding"):
                key = "png_enc"
            elif header[0] == "Category":
                key = "png_cat"
        if not key:
            continue
        nlabel = 3 if key in ("jpeg_enc", "jpeg_dec") else 2 if key in ("png_dec", "png_enc") else 1
        out["perf"][key] = {
            "labels": header[:nlabel],
            "columns": header[nlabel:],
            "rows": [
                {"label": r[:nlabel], "raw": r[nlabel:], "ratio": [pct(c) for c in r[nlabel:]]}
                for r in rows
            ],
            "notes": notes,
        }
    # Optimization logs: "- <change> ([sha](url), ...): <gain>."
    out["log"] = {}
    section = ""
    for line in lines:
        if line.startswith("#"):
            section = line.lstrip("#").strip()
        elif section.endswith("optimization log") and line.startswith("- "):
            m = re.match(r"^- (.*?) \(((?:\[[0-9a-f]+\]\([^)]*\)(?:, )?)+)\): (.*)$", line)
            assert m, line
            out["log"].setdefault(section.split()[0].lower(), []).append({
                "change": m.group(1),
                "commits": re.findall(r"\[([0-9a-f]+)\]", m.group(2)),
                "gain": m.group(3).rstrip("."),
            })
    for key in ("jpeg_enc", "jpeg_dec", "jpeg_enc_cfg", "jpeg_dec_cfg", "png_dec", "png_enc", "png_cat"):
        assert key in out["perf"], key
    (ROOT / "docs" / "data.js").write_text(
        "// Generated by docs/gen_data.py from README.md; do not edit.\n"
        "window.VIO_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
